package com.example.sysarch.solver;

import java.util.List;
import java.util.Map;

/**
 * A numeric solver behind the parametric model (spec P3 §3.2). We model; the solver solves: no equation solving,
 * differentiation or optimisation is implemented in Java (§1.1). Implementations: {@link PythonSolver} (SciPy, the
 * spec's {@code solver/python_solver.py} in its own process), {@link ModelicaSolver} (OpenModelica's {@code omc}),
 * {@link RemoteHttpSolver} (an HTTP solver service with the Python script's JSON contract).
 */
public interface ConstraintSolver {

    /** {@code python}, {@code modelica} or {@code remote} (the OpenAPI's {@code solver} values). */
    String id();

    /** Stateless; may run in parallel. */
    SolveResult solve(SolveRequest request);

    /** The unit whitelist (spec §3.2), the same for every solver. */
    default boolean supports(String unit) {
        return Units.supported(unit);
    }

    /** False when the solver is not configured on this installation (answered 503). */
    default boolean available() {
        return true;
    }

    /**
     * What a solver gets: {@code expression} is generated by {@link SolveSystem} from validated equations (one residual
     * per target, the form the spec's Python script expects), never the user's text; {@code modelica} the same system as a
     * Modelica model; {@code inputs} every known variable.
     */
    record SolveRequest(String expression, String modelica, Map<String, Double> inputs, List<String> targets, double tolerance, int maxIterations) {
    }

    /** What a solver answers (the spec's response, keyed by solver variable). */
    record SolveResult(boolean converged, Map<String, Double> outputs, Map<String, Double> residuals, int iterations, String log) {
    }

    /** The solver could not run or answered nonsense (a 422 for the caller, with the reason). */
    class SolverFailure extends RuntimeException {

        private static final long serialVersionUID = 1L;

        public SolverFailure(String message) {
            super(message);
        }
    }

    /** The solver did not answer within the time limit (504; nothing is written back). */
    class SolverTimeout extends RuntimeException {

        private static final long serialVersionUID = 1L;

        public SolverTimeout(String message) {
            super(message);
        }
    }
}
