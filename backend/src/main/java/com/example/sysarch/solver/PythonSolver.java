package com.example.sysarch.solver;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.TimeUnit;

/**
 * {@code python}: the spec's {@code solver/python_solver.py} (P3 §3.4, verbatim), one process per solve.
 * <ul>
 * <li>{@code -I} (isolated: no environment variables, no user site, no current directory on the path), an empty
 * environment but for what Windows needs to start a process, a fresh temporary working directory;</li>
 * <li>the request on stdin, the answer on stdout (JSON);</li>
 * <li>killed after the timeout (30 s): {@link SolverTimeout}, nothing is written back.</li>
 * </ul>
 * The code it executes is generated by {@link SolveSystem} from scanned equations, and the script runs it with no
 * builtins. Network and file-system isolation is the deployment's (the Helm chart's solver pod); see the runbook.
 */
public class PythonSolver implements ConstraintSolver {

    static final String SCRIPT = "solver/python_solver.py";

    private final String python;

    private final Duration timeout;

    private final ObjectMapper json;

    private final Path script;

    public PythonSolver(String python, Duration timeout, ObjectMapper json) {
        this.python = python == null ? "" : python.strip();
        this.timeout = timeout;
        this.json = json;
        this.script = this.python.isEmpty() ? null : extract();
    }

    @Override
    public String id() {
        return "python";
    }

    @Override
    public boolean available() {
        return !this.python.isEmpty() && Files.isRegularFile(Path.of(this.python));
    }

    @Override
    public SolveResult solve(SolveRequest request) {
        Path work = null;
        Process process = null;
        try {
            work = Files.createTempDirectory("sysarch-solve-");
            ProcessBuilder builder = new ProcessBuilder(this.python, "-I", this.script.toString()).directory(work.toFile()).redirectErrorStream(false);
            Map<String, String> env = builder.environment();
            String systemRoot = env.get("SystemRoot");
            env.clear();
            if (systemRoot != null) {
                env.put("SystemRoot", systemRoot); // Windows needs it to start a process at all
            }
            process = builder.start();
            Process running = process;
            CompletableFuture<byte[]> out = CompletableFuture.supplyAsync(() -> readAll(running.getInputStream()));
            CompletableFuture<byte[]> err = CompletableFuture.supplyAsync(() -> readAll(running.getErrorStream()));
            try (OutputStream in = process.getOutputStream()) {
                in.write(this.json.writeValueAsBytes(requestJson(this.json, request)));
            }
            if (!process.waitFor(this.timeout.toMillis(), TimeUnit.MILLISECONDS)) {
                process.descendants().forEach(ProcessHandle::destroyForcibly);
                process.destroyForcibly();
                throw new SolverTimeout("求解超时：" + this.timeout.toSeconds() + " 秒内没有结果，已终止求解进程，未写回任何值");
            }
            String stdout = new String(out.join(), StandardCharsets.UTF_8).strip();
            if (process.exitValue() != 0 || stdout.isEmpty()) {
                throw new SolverFailure("求解进程出错（退出码 " + process.exitValue() + "）：" + lastLine(new String(err.join(), StandardCharsets.UTF_8)));
            }
            return result(this.json.readTree(stdout));
        } catch (IOException e) {
            throw new SolverFailure("无法运行 Python 求解：" + e.getMessage());
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new SolverFailure("求解被中断");
        } finally {
            if (process != null && process.isAlive()) {
                process.destroyForcibly();
            }
            if (work != null) {
                try (var files = Files.walk(work)) {
                    files.sorted(java.util.Comparator.reverseOrder()).forEach(p -> p.toFile().delete());
                } catch (IOException e) {
                    // a temporary directory; the OS cleans up
                }
            }
        }
    }

    /** The script's input (spec §3.4): expression, inputs, targets, options. Also the remote solver's request. */
    static ObjectNode requestJson(ObjectMapper json, SolveRequest request) {
        ObjectNode body = json.createObjectNode();
        body.put("expression", request.expression());
        ObjectNode inputs = body.putObject("inputs");
        request.inputs().forEach(inputs::put);
        request.targets().forEach(body.putArray("targets")::add);
        ObjectNode options = body.putObject("options");
        options.put("tolerance", request.tolerance());
        options.put("maxIterations", request.maxIterations());
        return body;
    }

    /** The script's output (spec §3.4); also the remote solver's response. */
    static SolveResult result(JsonNode node) {
        if (!node.has("converged") || !node.path("outputs").isObject()) {
            throw new SolverFailure("求解器的回答不完整：" + node);
        }
        Map<String, Double> outputs = new LinkedHashMap<>();
        node.path("outputs").fields().forEachRemaining(e -> outputs.put(e.getKey(), e.getValue().asDouble()));
        Map<String, Double> residuals = new LinkedHashMap<>();
        node.path("residuals").fields().forEachRemaining(e -> residuals.put(e.getKey(), e.getValue().asDouble()));
        return new SolveResult(node.path("converged").asBoolean(), outputs, residuals, node.path("iterations").asInt(), node.path("solverLog").asText(""));
    }

    private static Path extract() {
        try (InputStream in = PythonSolver.class.getClassLoader().getResourceAsStream(SCRIPT)) {
            if (in == null) {
                throw new IllegalStateException(SCRIPT + " is not packaged with the backend");
            }
            Path dir = Files.createTempDirectory("sysarch-solver-");
            Path file = dir.resolve("python_solver.py");
            Files.write(file, in.readAllBytes());
            file.toFile().deleteOnExit();
            dir.toFile().deleteOnExit();
            return file;
        } catch (IOException e) {
            throw new IllegalStateException("cannot extract " + SCRIPT + ": " + e.getMessage(), e);
        }
    }

    private static byte[] readAll(InputStream in) {
        try {
            return in.readAllBytes();
        } catch (IOException e) {
            return new byte[0];
        }
    }

    private static String lastLine(String text) {
        String[] lines = text.strip().split("\\R");
        return lines.length == 0 || lines[lines.length - 1].isBlank() ? "（无输出）" : lines[lines.length - 1];
    }
}
