package com.example.vsm;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.yaml.snakeyaml.error.MarkedYAMLException;

/**
 * View templates (spec P1 §3.1, T3 step 1): one template plus one parameter file per view, so views that differ only
 * in layer and colours cannot drift apart. {@code views/_templates/*.params.yaml} names a template in the same
 * directory, an output file in {@code views/} and the parameter values:
 *
 * <pre>
 * template: "layer-architecture.vsm.tpl.yaml"
 * output: "la-architecture.vsm.yaml"
 * params:
 *   id: "la-architecture"
 *   ...
 * </pre>
 *
 * A template is plain text in which {@code ${name}} is replaced by a parameter. There is nothing else: no conditions,
 * loops or expressions (T3: "模板中禁止出现硬编码颜色以外的分支逻辑"), so every difference between the views is a
 * parameter. An unknown or unused parameter, or any other {@code ${...}}, is an error with {@code file:line}.
 *
 * <p>The outputs are committed like the generated Java: {@code generateViews} writes them, and every compile checks that
 * the committed file equals its expansion, so a hand edit of a generated view fails the build.
 */
final class ViewTemplates {

    static final String DIRECTORY = "_templates";

    static final String PARAMS_SUFFIX = ".params.yaml";

    private static final Pattern PLACEHOLDER = Pattern.compile("\\$\\{([^}]*)}");

    private static final Pattern NAME = Pattern.compile("[a-z][A-Za-z0-9]*");

    /** One expanded view: the file it belongs in and its text. */
    record Expansion(Path output, String content, String paramsFile) {
    }

    private ViewTemplates() {
    }

    /**
     * Expands every parameter file in {@code viewsDir/_templates}; adds problems to {@code diagnostics}.
     *
     * @param display how a path is shown in messages
     */
    static List<Expansion> expand(Path viewsDir, Function<Path, String> display, List<Diagnostic> diagnostics) throws IOException {
        Path directory = viewsDir.resolve(DIRECTORY);
        if (!Files.isDirectory(directory)) {
            return List.of();
        }
        List<Path> paramFiles;
        try (Stream<Path> stream = Files.list(directory)) {
            paramFiles = stream.filter(p -> p.getFileName().toString().endsWith(PARAMS_SUFFIX)).sorted().toList();
        }
        List<Expansion> expansions = new ArrayList<>();
        Set<String> outputs = new LinkedHashSet<>();
        for (Path paramFile : paramFiles) {
            String file = display.apply(paramFile);
            YamlNode params;
            try {
                params = YamlNode.parse(Files.readString(paramFile, StandardCharsets.UTF_8));
            } catch (MarkedYAMLException e) {
                diagnostics.add(new Diagnostic(file, e.getProblemMark() == null ? 1 : e.getProblemMark().getLine() + 1, "YAML syntax error: " + e.getProblem()));
                continue;
            }
            if (params == null || !params.isMapping() || params.text("template") == null || params.text("output") == null || params.get("params") == null
                    || !params.get("params").isMapping()) {
                diagnostics.add(new Diagnostic(file, 1, "a parameter file needs template, output and a params mapping"));
                continue;
            }
            for (String key : params.keys()) {
                if (!Set.of("template", "output", "params").contains(key)) {
                    diagnostics.add(new Diagnostic(file, params.keyLine(key), "unknown key '" + key + "' (expected template, output, params)"));
                }
            }
            String output = params.text("output");
            if (!output.endsWith(VsmCompiler.YAML_SUFFIX) || output.contains("/") || output.contains("\\")) {
                diagnostics.add(new Diagnostic(file, params.keyLine("output"), "output must be a file name ending in " + VsmCompiler.YAML_SUFFIX));
                continue;
            }
            if (!outputs.add(output)) {
                diagnostics.add(new Diagnostic(file, params.keyLine("output"), "output '" + output + "' is generated by another parameter file too"));
                continue;
            }
            Path template = directory.resolve(params.text("template")).normalize();
            if (!template.getParent().equals(directory.normalize()) || !Files.isRegularFile(template)) {
                diagnostics.add(new Diagnostic(file, params.keyLine("template"), "template '" + params.text("template") + "' not found in " + display.apply(directory)));
                continue;
            }
            YamlNode values = params.get("params");
            Map<String, String> byName = new LinkedHashMap<>();
            for (String name : values.keys()) {
                if (!NAME.matcher(name).matches() || values.text(name) == null) {
                    diagnostics.add(new Diagnostic(file, values.keyLine(name), "parameter '" + name + "' must be a lowerCamel name with a scalar value"));
                } else {
                    byName.put(name, values.text(name));
                }
            }
            String content = substitute(display.apply(template), Files.readString(template, StandardCharsets.UTF_8), byName, diagnostics);
            Set<String> unused = new LinkedHashSet<>(byName.keySet());
            Matcher used = PLACEHOLDER.matcher(Files.readString(template, StandardCharsets.UTF_8));
            while (used.find()) {
                unused.remove(used.group(1));
            }
            for (String name : unused) {
                diagnostics.add(new Diagnostic(file, values.keyLine(name), "parameter '" + name + "' is not used by " + params.text("template")));
            }
            if (content != null) {
                expansions.add(new Expansion(viewsDir.resolve(output), content, file));
            }
        }
        return expansions;
    }

    /** {@code ${name}} replaced line by line, so an error names the template line. Null if anything was wrong. */
    private static String substitute(String templateFile, String template, Map<String, String> params, List<Diagnostic> diagnostics) {
        StringBuilder out = new StringBuilder();
        boolean ok = true;
        String[] lines = template.split("\n", -1);
        for (int i = 0; i < lines.length; i++) {
            Matcher matcher = PLACEHOLDER.matcher(lines[i]);
            StringBuilder line = new StringBuilder();
            while (matcher.find()) {
                String name = matcher.group(1);
                String value = params.get(name);
                if (!NAME.matcher(name).matches()) {
                    diagnostics.add(new Diagnostic(templateFile, i + 1, "'${" + name + "}' is not a parameter: templates only substitute ${name}"));
                    ok = false;
                } else if (value == null) {
                    diagnostics.add(new Diagnostic(templateFile, i + 1, "unknown parameter '" + name + "'"));
                    ok = false;
                } else {
                    matcher.appendReplacement(line, Matcher.quoteReplacement(value));
                }
            }
            matcher.appendTail(line);
            if (line.indexOf("<#") >= 0 || line.indexOf("{%") >= 0) {
                diagnostics.add(new Diagnostic(templateFile, i + 1, "template directives are not allowed: templates only substitute ${name}"));
                ok = false;
            }
            out.append(line);
            if (i < lines.length - 1) {
                out.append('\n');
            }
        }
        return ok ? out.toString() : null;
    }

    /** Writes the expansions that differ from what is on disk; returns how many were written. */
    static int write(List<Expansion> expansions) throws IOException {
        int written = 0;
        for (Expansion expansion : expansions) {
            if (!Files.isRegularFile(expansion.output()) || !Files.readString(expansion.output(), StandardCharsets.UTF_8).equals(expansion.content())) {
                Files.writeString(expansion.output(), expansion.content(), StandardCharsets.UTF_8);
                written++;
            }
        }
        return written;
    }

    /** An error for each committed output that is missing or differs from its expansion. */
    static void checkCommitted(List<Expansion> expansions, Function<Path, String> display, List<Diagnostic> diagnostics) throws IOException {
        for (Expansion expansion : expansions) {
            boolean fresh = Files.isRegularFile(expansion.output())
                    && Files.readString(expansion.output(), StandardCharsets.UTF_8).equals(expansion.content());
            if (!fresh) {
                diagnostics.add(new Diagnostic(display.apply(expansion.output()), 1, "differs from its template expansion (" + expansion.paramsFile()
                        + "); edit the template or the parameters, not this file, then run ./gradlew :vsm-compiler:generateViews"));
            }
        }
    }
}
